use bracket_lib::terminal::VirtualKeyCode as Key;

pub fn key_to_char(key: &Key) -> Option<char> {
	Some(match key {
		Key::A => 'a',
		Key::B => 'b',
		Key::C => 'c',
		Key::D => 'd',
		Key::E => 'e',
		Key::F => 'f',
		Key::G => 'g',
		Key::H => 'h',
		Key::I => 'i',
		Key::J => 'j',
		Key::K => 'k',
		Key::L => 'l',
		Key::M => 'm',
		Key::N => 'n',
		Key::O => 'o',
		Key::P => 'p',
		Key::Q => 'q',
		Key::R => 'r',
		Key::S => 's',
		Key::T => 't',
		Key::U => 'u',
		Key::V => 'v',
		Key::W => 'w',
		Key::X => 'x',
		Key::Y => 'y',
		Key::Z => 'z',
		Key::Key0 | Key::Numpad0 => '0',
		Key::Key1 | Key::Numpad1 => '1',
		Key::Key2 | Key::Numpad2 => '2',
		Key::Key3 | Key::Numpad3 => '3',
		Key::Key4 | Key::Numpad4 => '4',
		Key::Key5 | Key::Numpad5 => '5',
		Key::Key6 | Key::Numpad6 => '6',
		Key::Key7 | Key::Numpad7 => '7',
		Key::Key8 | Key::Numpad8 => '8',
		Key::Key9 | Key::Numpad9 => '9',
		Key::Space => ' ',
		_ => return None,
	})
}
